let supabaseInstance = null;

function getSupabaseClient() {
  if (supabaseInstance) return supabaseInstance;

  const url = localStorage.getItem('VITAL_SUPABASE_URL') || DEFAULT_SUPABASE_URL;
  const key = localStorage.getItem('VITAL_SUPABASE_KEY') || DEFAULT_SUPABASE_KEY;

  if (url && key && window.supabase) {
    try {
      supabaseInstance = window.supabase.createClient(url, key);
      return supabaseInstance;
    } catch (e) {
      console.error('Error al inicializar cliente de Supabase:', e);
    }
  }
  return null;
}

function isSupabaseConfigured() {
  const url = localStorage.getItem('VITAL_SUPABASE_URL') || DEFAULT_SUPABASE_URL;
  const key = localStorage.getItem('VITAL_SUPABASE_KEY') || DEFAULT_SUPABASE_KEY;
  return !!(url && key);
}

async function fetchDonations() {
  const client = getSupabaseClient();
  if (client) {
    try {
      const { data, error } = await client
        .from('donaciones')
        .select('*')
        .order('created_at', { ascending: false });

      if (!error && Array.isArray(data) && data.length > 0) {
        // Sincronizar copia en localStorage
        localStorage.setItem('VITAL_DONATIONS_CACHE', JSON.stringify(data));
        return data;
      }
    } catch (err) {
      console.warn('Fallo de conexión con Supabase. Usando respaldo local:', err);
    }
  }

  // Respaldo en LocalStorage
  const localData = localStorage.getItem('VITAL_DONATIONS_CACHE');
  if (localData) {
    try {
      return JSON.parse(localData);
    } catch (e) {
      console.error('Error parseando caché local:', e);
    }
  }

  // Datos semilla iniciales
  localStorage.setItem('VITAL_DONATIONS_CACHE', JSON.stringify(INITIAL_MOCK_DATA));
  return INITIAL_MOCK_DATA;
}

async function saveDonation(newItem) {
  const client = getSupabaseClient();
  let savedInSupabase = false;

  const payload = {
    type: newItem.type || 'donacion',
    title: newItem.title,
    category: newItem.category,
    quantity: newItem.quantity,
    expiry_date: newItem.expiry_date || null,
    city: newItem.city,
    phone: newItem.phone,
    description: newItem.description || '',
    status: newItem.status || 'disponible',
    created_at: new Date().toISOString()
  };

  if (client) {
    try {
      const { data, error } = await client
        .from('donaciones')
        .insert([payload])
        .select();

      if (!error && data && data.length > 0) {
        payload.id = data[0].id.toString();
        savedInSupabase = true;
      } else if (error) {
        console.warn('Aviso Supabase insert:', error.message);
      }
    } catch (err) {
      console.error('Error insertando en Supabase:', err);
    }
  }

  if (!savedInSupabase) {
    payload.id = 'loc_' + Date.now().toString();
  }

  // Guardar en caché local
  const current = await fetchDonations();
  const updated = [payload, ...current.filter(item => item.id.toString() !== payload.id.toString())];
  localStorage.setItem('VITAL_DONATIONS_CACHE', JSON.stringify(updated));

  return payload;
}

async function updateDonationStatus(id, newStatus) {
  const client = getSupabaseClient();

  if (client && !id.toString().startsWith('loc_')) {
    try {
      await client
        .from('donaciones')
        .update({ status: newStatus })
        .eq('id', id);
    } catch (err) {
      console.warn('Error al actualizar estado en Supabase:', err);
    }
  }

  // Actualizar en caché local
  const current = await fetchDonations();
  const updated = current.map(item => {
    if (item.id.toString() === id.toString()) {
      return { ...item, status: newStatus };
    }
    return item;
  });

  localStorage.setItem('VITAL_DONATIONS_CACHE', JSON.stringify(updated));
  return updated;
}

